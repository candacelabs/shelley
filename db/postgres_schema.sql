-- SQLite's FTS5 table messages_fts, as PostgreSQL full-text search: the
-- extracted text of each user and agent message, and its tsvector.
CREATE TABLE messages_fts (
    message_id TEXT PRIMARY KEY REFERENCES messages(message_id) ON DELETE CASCADE,
    text TEXT NOT NULL,
    document tsvector GENERATED ALWAYS AS (to_tsvector('english', text)) STORED
);
CREATE INDEX idx_messages_fts_document ON messages_fts USING gin (document);

-- Shelley's FTS5 triggers, as one: a user or agent message's searchable text
-- is every Text and Thinking string anywhere in its user_data or llm_data.
CREATE FUNCTION messages_fts_sync() RETURNS trigger LANGUAGE plpgsql AS $sync$
BEGIN
  IF TG_OP <> 'INSERT' THEN
    DELETE FROM messages_fts WHERE message_id = OLD.message_id;
  END IF;
  IF TG_OP <> 'DELETE' AND NEW.type IN ('user', 'agent')
     AND COALESCE(NEW.user_data, NEW.llm_data) IS JSON THEN
    INSERT INTO messages_fts (message_id, text)
    SELECT NEW.message_id, string_agg(value #>> '{}', ' ')
    FROM (
      SELECT jsonb_path_query(COALESCE(NEW.user_data, NEW.llm_data)::jsonb, 'strict $.**.Text') AS value
      UNION ALL
      SELECT jsonb_path_query(COALESCE(NEW.user_data, NEW.llm_data)::jsonb, 'strict $.**.Thinking')
    ) strings
    WHERE jsonb_typeof(value) = 'string' AND value #>> '{}' <> ''
    HAVING count(*) > 0;
  END IF;
  RETURN NULL;
END
$sync$;
CREATE TRIGGER messages_fts_sync AFTER INSERT OR UPDATE OR DELETE ON messages
  FOR EACH ROW EXECUTE FUNCTION messages_fts_sync();

