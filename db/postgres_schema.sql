-- SQLite's JSON functions, for the hand-written queries Shelley keeps from
-- upstream (they store JSON as TEXT and read it with these): the same names
-- and the same answers, on text, so those queries run here unchanged. A path
-- is SQLite's '$.a.b' (object keys only, as Shelley's queries use).
CREATE FUNCTION json_path(path TEXT) RETURNS TEXT[]
LANGUAGE sql IMMUTABLE STRICT AS $$
    SELECT CASE WHEN path = '$' THEN ARRAY[]::TEXT[]
                ELSE string_to_array(substr(path, 3), '.') END
$$;

-- 1 when text is well-formed JSON, else 0 (SQLite's json_valid).
CREATE FUNCTION json_valid(document TEXT) RETURNS BOOLEAN
LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
    IF document IS NULL THEN RETURN NULL; END IF;
    PERFORM document::jsonb;
    RETURN TRUE;
EXCEPTION WHEN others THEN
    RETURN FALSE;
END;
$$;

-- The value at path: a string as its text, anything else as JSON text, and
-- NULL for a missing path or a JSON null (SQLite's json_extract).
CREATE FUNCTION json_extract(document TEXT, path TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE STRICT AS $$
    SELECT document::jsonb #>> json_path(path)
$$;

-- The type of the value at path, as SQLite names it ('null', 'true',
-- 'false', 'integer', 'real', 'text', 'array', 'object'), or NULL when the
-- path is missing (SQLite's json_type).
CREATE FUNCTION json_type(document TEXT, path TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE STRICT AS $$
    SELECT CASE jsonb_typeof(value)
               WHEN 'string' THEN 'text'
               WHEN 'boolean' THEN value::text
               WHEN 'number' THEN CASE WHEN value::text ~ '^-?[0-9]+$' THEN 'integer' ELSE 'real' END
               ELSE jsonb_typeof(value) END
    FROM (SELECT document::jsonb #> json_path(path) AS value) AS found
$$;

-- The elements of the array (or members of the object) at path, each value
-- as JSON text, a string as its text (SQLite's json_each).
CREATE FUNCTION json_each(document TEXT, path TEXT) RETURNS TABLE (key TEXT, value TEXT)
LANGUAGE sql IMMUTABLE STRICT AS $$
    SELECT NULL::TEXT, CASE WHEN jsonb_typeof(element) = 'string' THEN element #>> '{}' ELSE element::text END
    FROM jsonb_array_elements(CASE WHEN jsonb_typeof(document::jsonb #> json_path(path)) = 'array'
                                   THEN document::jsonb #> json_path(path) ELSE '[]'::jsonb END) AS element
    UNION ALL
    SELECT member.key, CASE WHEN jsonb_typeof(member.value) = 'string' THEN member.value #>> '{}' ELSE member.value::text END
    FROM jsonb_each(CASE WHEN jsonb_typeof(document::jsonb #> json_path(path)) = 'object'
                         THEN document::jsonb #> json_path(path) ELSE '{}'::jsonb END) AS member
$$;

CREATE FUNCTION json_each(document TEXT) RETURNS TABLE (key TEXT, value TEXT)
LANGUAGE sql IMMUTABLE STRICT AS $$
    SELECT * FROM json_each(document, '$')
$$;

-- document with the value at path set to a JSON string (SQLite's json_set
-- with a text value).
CREATE FUNCTION json_set(document TEXT, path TEXT, setting TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE AS $$
    SELECT jsonb_set(COALESCE(document, '{}')::jsonb, json_path(path), to_jsonb(setting), TRUE)::text
$$;

