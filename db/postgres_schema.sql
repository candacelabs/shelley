-- Shelley's store on PostgreSQL: every table in schema shelley. Shelley's
-- upstream keeps its store in SQLite (db/schema holds those migrations);
-- this fork keeps it in PostgreSQL, the embedder's database, so a host
-- process and Shelley share one server.
--
-- Apply it once, in one transaction (CreateSchema does, when the schema
-- has no conversations table yet):
--
--   psql "$DATABASE_URL" --single-transaction -f db/postgres_schema.sql
--
-- csf applies the same DDL as its migration 057_shelley_store; csf's spec
-- shelley_schema_test.go keeps the two identical.

DO $schema$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'shelley') THEN
    CREATE SCHEMA shelley;
  END IF;
END
$schema$;
SET LOCAL search_path TO shelley;

